let musikSudahMulai = false;

// Fungsi untuk membuat bintang/daun melayang
function buatHiasanBergerak() {
    const wadahHiasan = document.createElement('div');
    wadahHiasan.className = 'hiasan-bergerak';
    document.body.appendChild(wadahHiasan);

    const simbolPartikel = ['✨', '🌟', '🤍', '🌸', '🍂'];
    const jumlahPartikel = 15;

    for (let i = 0; i < jumlahPartikel; i++) {
        let partikel = document.createElement('div');
        partikel.className = 'partikel';
        partikel.innerText = simbolPartikel[Math.floor(Math.random() * simbolPartikel.length)];
        
        partikel.style.left = Math.random() * 100 + 'vw';
        partikel.style.animationDuration = (Math.random() * 6 + 6) + 's';
        partikel.style.animationDelay = (Math.random() * 5) + 's';
        partikel.style.fontSize = (Math.random() * 10 + 15) + 'px';
        
        wadahHiasan.appendChild(partikel);
    }
}

// Fungsi untuk merender 12 tombol kartu
function buatMenu() {
    const wadah = document.getElementById('wadah-tombol');
    
    daftarPesan.forEach(pesan => {
        const tombol = document.createElement('button');
        tombol.innerText = pesan.judul;
        tombol.className = 'kartu-pesan';
        tombol.onclick = () => bukaPesan(pesan.id);
        wadah.appendChild(tombol);
    });
}

// Fungsi saat salah satu kartu pesan diklik
function bukaPesan(id) {
    if (!musikSudahMulai) {
        document.getElementById('musik-bg').play();
        musikSudahMulai = true;
    }

    const pesanDipilih = daftarPesan.find(p => p.id === id);
    
    document.getElementById('judul-surat').innerText = pesanDipilih.judul;
    const isiSurat = document.getElementById('isi-surat');
    isiSurat.innerHTML = pesanDipilih.isi;
    isiSurat.className = pesanDipilih.gayaTulisan; 

    document.getElementById('layar-menu').classList.add('tersembunyi');
    document.getElementById('layar-pesan').classList.remove('tersembunyi');
}

// Fungsi untuk kembali ke menu awal
function kembaliKeMenu() {
    document.getElementById('layar-pesan').classList.add('tersembunyi');
    document.getElementById('layar-menu').classList.remove('tersembunyi');
}

// Jalankan saat web dimuat
buatHiasanBergerak();
buatMenu();